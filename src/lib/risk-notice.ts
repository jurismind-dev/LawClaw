export function isRiskNoticePlatform(platform: NodeJS.Platform | string): boolean {
  return platform === 'darwin' || platform === 'win32';
}

export function hasAcceptedRiskNotice(acceptedVersion: string | null | undefined): boolean {
  return typeof acceptedVersion === 'string' && acceptedVersion.trim().length > 0;
}

export function shouldShowRiskNotice(
  platform: NodeJS.Platform | string,
  acceptedVersion: string | null | undefined,
): boolean {
  return isRiskNoticePlatform(platform) && !hasAcceptedRiskNotice(acceptedVersion);
}
